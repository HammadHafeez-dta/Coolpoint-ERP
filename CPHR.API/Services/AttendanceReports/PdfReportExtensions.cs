using System;
using System.Collections.Generic;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace SaftHR.API.Services.AttendanceReports
{
    public static class PdfReportExtensions
    {
        // Brand & Theme Colors
        public const string PrimaryColor = "#1E3A8A";
        public const string SubtitleColor = "#3B82F6";
        public const string DefaultBorderColor = "#000000";

        /// <summary>
        /// Applies standard page setup: margins, page background, font, and orientation.
        /// </summary>
        public static PageDescriptor ApplyStandardPage(
            this PageDescriptor page,
            PageSize pageSize,
            float marginCm = 1.0f,
            float defaultFontSize = 8f,
            string defaultFontColor = "#374151")
        {
            page.Size(pageSize);
            page.Margin(marginCm, Unit.Centimetre);
            page.PageColor(Colors.White);
            page.DefaultTextStyle(x => x.FontSize(defaultFontSize).FontFamily("Arial").FontColor(defaultFontColor));
            return page;
        }

        /// <summary>
        /// Renders the modern two-column report header with organization title, report title, site, and date.
        /// </summary>
        public static void RenderStandardHeader(
            this IContainer headerContainer,
            string reportTitle,
            string site,
            string dateRangeText,
            string? siteFullName = null)
        {
            string displayOrgName = !string.IsNullOrWhiteSpace(siteFullName) ? siteFullName : "CoolPoint";
            headerContainer.Column(col =>
            {
                col.Item().Row(row =>
                {
                    row.RelativeItem().Column(titleCol =>
                    {
                        titleCol.Item().Text(displayOrgName).Bold().FontSize(14).FontColor(PrimaryColor);
                        titleCol.Item().Text($"{reportTitle}: {dateRangeText}").SemiBold().FontSize(10).FontColor(SubtitleColor);
                    });
                    row.ConstantItem(120).AlignRight().Column(siteCol =>
                    {
                        siteCol.Item().Text($"SITE: {site}").Bold().FontSize(9).FontColor(Colors.Grey.Medium);
                        siteCol.Item().Text($"Date: {DateTime.Now:dd MMM yyyy}").FontSize(8).FontColor(Colors.Grey.Medium);
                    });
                });
                col.Item().PaddingVertical(3).LineHorizontal(1).LineColor(Colors.Grey.Lighten2);
            });
        }

        /// <summary>
        /// Renders school boxed header (e.g. for time cards, individual cards, etc.).
        /// </summary>
        public static void RenderSchoolBoxedHeader(
            this IContainer headerContainer,
            string subtitle,
            string schoolName = "CoolPoint")
        {
            headerContainer.Column(col =>
            {
                col.Item().AlignCenter().Border(1).BorderColor(Colors.Black).Padding(5).Column(box =>
                {
                    box.Item().AlignCenter().Text(schoolName).Bold().FontSize(12).FontColor(Colors.Black);
                });
                col.Item().AlignCenter().PaddingTop(4).Text(subtitle).Bold().FontSize(9).Underline().FontColor(Colors.Black);
            });
        }

        /// <summary>
        /// Renders school unboxed header (e.g. for detail breakdown and summary reports).
        /// </summary>
        public static void RenderSchoolSimpleHeader(
            this IContainer headerContainer,
            string subtitle,
            string schoolName = "CoolPoint")
        {
            headerContainer.Column(col =>
            {
                col.Item().AlignCenter().Text(schoolName).Bold().FontSize(12);
                col.Item().AlignCenter().PaddingTop(3).Text(subtitle).Bold().FontSize(9).Underline();
            });
        }

        /// <summary>
        /// Renders standard footer with page number and generator stamp.
        /// </summary>
        public static void RenderStandardFooter(
            this IContainer footerContainer,
            string generatedBy = "Generated by SAFT HRMS System")
        {
            footerContainer.Column(col =>
            {
                col.Item().LineHorizontal(1).LineColor(Colors.Grey.Lighten2);
                col.Item().PaddingTop(3).Row(row =>
                {
                    row.RelativeItem().Text(generatedBy).FontSize(8).FontColor(Colors.Grey.Medium);
                    row.RelativeItem().AlignRight().Text(x =>
                    {
                        x.Span("Page ").FontSize(8).FontColor(Colors.Grey.Medium);
                        x.CurrentPageNumber().FontSize(8).FontColor(Colors.Grey.Medium);
                        x.Span(" of ").FontSize(8).FontColor(Colors.Grey.Medium);
                        x.TotalPages().FontSize(8).FontColor(Colors.Grey.Medium);
                    });
                });
            });
        }

        /// <summary>
        /// Styles a standard header cell in navy blue with white bold text.
        /// </summary>
        public static IContainer HeaderCell(this IContainer container, string backgroundColor = PrimaryColor, float padding = 4f)
        {
            return container.Background(backgroundColor).Padding(padding);
        }

        /// <summary>
        /// Styles an alternating data row cell.
        /// </summary>
        public static IContainer RowCell(this IContainer container, int rowIndex, float padding = 4f)
        {
            var bg = rowIndex % 2 == 0 ? Colors.Grey.Lighten5 : Colors.White;
            return container.Background(bg).Padding(padding);
        }

        /// <summary>
        /// Styles a bordered cell for grid-style reports.
        /// </summary>
        public static IContainer BorderedCell(this IContainer container, float borderWidth = 0.5f, string borderColor = DefaultBorderColor, float padding = 3f)
        {
            return container.Border(borderWidth).BorderColor(borderColor).Padding(padding);
        }

        /// <summary>
        /// Helper to render an empty state message across table columns.
        /// </summary>
        public static void RenderEmptyState(this TableDescriptor table, uint columnSpan, string message = "No records found.")
        {
            table.Cell().ColumnSpan(columnSpan).Padding(20).AlignCenter().Text(message).Italic().FontColor(Colors.Grey.Medium);
        }

        /// <summary>
        /// Generates a list of start dates for each month in the range.
        /// </summary>
        public static List<DateTime> GetMonthRangeList(DateTime fromDate, DateTime toDate)
        {
            var list = new List<DateTime>();
            var startMonth = new DateTime(fromDate.Year, fromDate.Month, 1);
            var endMonth = new DateTime(toDate.Year, toDate.Month, 1);
            while (startMonth <= endMonth)
            {
                list.Add(startMonth);
                startMonth = startMonth.AddMonths(1);
            }
            return list;
        }
    }
}
